"""
Quiz dataset loader - handles loading quiz text samples from CSV files
"""
import os
import random
import pandas as pd
import logging

logger = logging.getLogger(__name__)

class QuizDatasetLoader:
    """
    Loads quiz text samples from CSV files
    """
    def __init__(self, data_dir='data', csv_files=None):
        self.data_dir = data_dir
        # quiz_samples.csv is the small curated starter set shipped in the
        # repo, so the quiz works out of the box with no download. It takes
        # precedence over everything else: the Kaggle CSVs
        # (ai_vs_human_text.csv / dataset.csv) are loaded only when the
        # curated set is absent, because their rows literally announce
        # their own label ("AI-generated content sample 1: This is an
        # example of text generated by ChatGPT..."), which defeats the
        # point of a guessing quiz.
        self.csv_files = csv_files or ['quiz_samples.csv', 'ai_vs_human_text.csv', 'dataset.csv']
        self.samples = []
        self.class_names = ['Human-written', 'AI-generated']
        self.load_samples()

    # Phrases inside the text itself that give the answer away. Any row
    # containing one is useless as a quiz question, so it is dropped from
    # every source file, including the curated set.
    GIVEAWAY_PATTERNS = [
        "generated by chatgpt",
        "generated by bard",
        "generated by claude",
        "generated by an ai",
        "ai-generated content sample",
        "human-written text sample",
        "as an ai language model",
        "as a language model",
        "this is an example of text generated",
        "this is an example of a text written",
        "in response to the prompt",
    ]
    
    def load_samples(self):
        """Load samples from CSV files"""
        all_samples = []
        
        for csv_file in self.csv_files:
            csv_path = os.path.join(self.data_dir, csv_file)
            if not os.path.exists(csv_path):
                logger.warning(f"CSV file not found: {csv_path}")
                continue
            
            try:
                df = pd.read_csv(csv_path)
                
                # Normalize column names
                text_col = None
                label_col = None
                
                # Find text column
                for col in ['text', 'content', 'body', 'essay']:
                    if col in df.columns:
                        text_col = col
                        break
                
                # Find label column. 'generated' is the column used by the
                # AI vs Human Text Kaggle dataset (0 = human, 1 = AI).
                for col in ['label', 'target', 'class', 'is_ai', 'generated']:
                    if col in df.columns:
                        label_col = col
                        break
                
                if text_col is None or label_col is None:
                    logger.warning(f"Could not find text or label column in {csv_file}")
                    continue
                
                # Normalize labels
                def normalize_label(label):
                    if pd.isna(label):
                        return None
                    label_str = str(label).strip().lower()
                    if label_str in ['ai-generated', 'ai', 'machine', 'generated', 'gpt', 'llm', 'chatgpt', '1']:
                        return 1  # AI-generated
                    elif label_str in ['human-written', 'human', 'person', 'authored', 'real', '0']:
                        return 0  # Human-written
                    return None
                
                # Process rows
                file_samples = []
                for idx, row in df.iterrows():
                    text = str(row[text_col]).strip()
                    label = normalize_label(row[label_col])

                    if text and text != 'nan' and label is not None:
                        # Drop rows whose text gives the answer away.
                        lowered = text.lower()
                        if any(p in lowered for p in self.GIVEAWAY_PATTERNS):
                            continue
                        file_samples.append({
                            'id': len(all_samples) + len(file_samples),
                            'text': text,
                            'label': label,
                            'label_name': self.class_names[label]
                        })

                logger.info(f"Loaded {len(file_samples)} usable rows from {csv_file} "
                            f"({len(df)} rows before filtering)")

                if csv_file == 'quiz_samples.csv' and file_samples:
                    # Curated set present: use it alone. The Space also
                    # holds the 1,000-row Kaggle file, whose rows self-label,
                    # so mixing it in would drown the good set (40 of 1,040).
                    all_samples = file_samples
                    break

                all_samples.extend(file_samples)
                
            except Exception as e:
                logger.error(f"Error loading {csv_file}: {e}")
                import traceback
                logger.error(traceback.format_exc())
        
        if all_samples:
            self.samples = all_samples
            logger.info(f"Loaded {len(self.samples)} quiz text samples total")
        else:
            logger.warning("No quiz samples available. Quiz will not work.")
            logger.warning("Please ensure CSV files exist in the data/ directory")
            self.samples = []
    
    def get_random_sample(self):
        """Get a random sample"""
        if not self.samples:
            return None, None
        idx = random.randint(0, len(self.samples) - 1)
        return idx, self.get_sample(idx)
    
    def get_sample(self, idx):
        """Get sample by index"""
        if idx < 0 or idx >= len(self.samples):
            return None
        return self.samples[idx]
    
    def __len__(self):
        return len(self.samples)

